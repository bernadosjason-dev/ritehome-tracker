#!/usr/bin/env node
/* Turns the "Ritehome Tracker Data" Google Sheet (the Apps Script backend's storage) into SQL that
   loads the same records into public.tracker_docs.

     node supabase/import-from-sheet.cjs sheet-values.json > import.sql

   sheet-values.json maps each tab name to its rows, header row first, exactly as the Sheets API
   values.get returns them: {"Projects": [[...headers], [...row]], "Expenses": ..., ...}.
   Tabs: Projects, Expenses, Company Vehicles, Company Fuel, Procurement Jobs, Procurement.

   Every id is kept, so links, receipts and procurement references keep working, and rows go in
   in sheet order, which is the order Code.gs listed them in. The "Data" column is the record;
   the other columns are only Code.gs's readable mirror and are ignored. Procurement keeps its
   revision and last change id, so an open tab's next save is checked against the right revision.

   Re-runnable: an id already in Supabase is overwritten with the Sheet's copy (run it again at
   cutover to pick up whatever was entered in the Sheet since the last run). Rows deleted from
   the Sheet are not deleted from Supabase. Receipt photos stay in Google Drive: their Drive ids
   keep working in the page. The output contains business data; don't commit it. */
'use strict';
const fs = require('node:fs');
const path = require('node:path');
require(path.join(__dirname, '..', 'procurement.js'));
const {normalize} = globalThis.ProcurementLogic;

const TABS = [
  // tab, collection, id column, parent column (or null), Data column
  ['Projects', 'projects', 0, null, 9],
  ['Expenses', 'expenses', 0, 1, 10],
  ['Company Vehicles', 'companyVehicles', 0, null, 5],
  ['Company Fuel', 'companyFuel', 0, null, 11],
  ['Procurement Jobs', 'procurementJobs', 0, null, 6]
];

function sqlText(s) { return "'" + String(s).replace(/'/g, "''") + "'"; }

function build(sheet) {
  const docs = [], problems = [];
  for (const [tab, collection, idCol, parentCol, dataCol] of TABS) {
    (sheet[tab] || []).slice(1).forEach((row, i) => {
      const id = String(row[idCol] || '');
      if (!id) return;
      let data;
      try { data = JSON.parse(row[dataCol]); } catch (e) { problems.push(`${tab} row ${i + 2} (${id}): Data isn't JSON, skipped`); return; }
      if (!data || typeof data !== 'object' || Array.isArray(data)) { problems.push(`${tab} row ${i + 2} (${id}): Data isn't an object, skipped`); return; }
      delete data.id;
      docs.push({collection, id, parent: parentCol == null ? null : String(row[parentCol] || ''), data, revision: 1});
    });
  }
  (sheet.Procurement || []).slice(1).forEach((row, i) => {
    const id = String(row[0] || ''), revision = Number(row[1]);
    if (!id) return;
    try {
      if (!Number.isInteger(revision) || revision < 1) throw Error('bad revision');
      const json = row.slice(4).map(c => { c = String(c ?? ''); if (c.indexOf('json:') !== 0) throw Error('bad chunk'); return c.slice(5); }).join('');
      docs.push({collection: 'procurement', id, parent: null, data: {mutationId: String(row[2] || ''), data: normalize(JSON.parse(json))}, revision});
    } catch (e) { problems.push(`Procurement row ${i + 2} (${id}): ${e.message}, skipped`); }
  });
  const ids = new Set(docs.filter(d => d.collection === 'projects').map(d => d.id));
  for (const d of docs) if (d.collection === 'expenses' && !ids.has(d.parent)) problems.push(`Expense ${d.id} points to missing project ${d.parent} (imported anyway, like the Sheet)`);
  return {docs, problems};
}

function toSql(docs) {
  const values = docs.map(d => `  (${sqlText(d.collection)}, ${sqlText(d.id)}, ${d.parent == null ? 'null' : sqlText(d.parent)}, ${sqlText(JSON.stringify(d.data))}::jsonb, ${d.revision})`);
  return [
    '-- Generated by supabase/import-from-sheet.cjs. Contains business data: do not commit.',
    'begin;',
    'insert into public.tracker_docs (collection, id, parent_id, data, revision) values',
    values.join(',\n'),
    '-- On a re-run the update trigger bumps revision, so a tab holding the old copy gets a conflict and refreshes.',
    'on conflict (collection, id) do update set parent_id = excluded.parent_id, data = excluded.data;',
    'commit;',
    ''
  ].join('\n');
}

if (require.main === module) {
  const file = process.argv[2];
  if (!file) { console.error('usage: node supabase/import-from-sheet.cjs sheet-values.json > import.sql'); process.exit(2); }
  const {docs, problems} = build(JSON.parse(fs.readFileSync(file, 'utf8')));
  problems.forEach(p => console.error('warning: ' + p));
  const counts = {};
  docs.forEach(d => { counts[d.collection] = (counts[d.collection] || 0) + 1; });
  console.error('records: ' + JSON.stringify(counts));
  process.stdout.write(toSql(docs));
}
module.exports = {build, toSql};
